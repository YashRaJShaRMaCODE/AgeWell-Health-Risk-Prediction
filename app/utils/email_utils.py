"""Email alert helper for high-risk patient notifications."""
import os
import smtplib
from email import encoders
from email.mime.base import MIMEBase
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText

from config.config import EMAIL_CONFIG


def send_high_risk_alert(patient_id, age, hr, bp, chol, bmi, health_score, food_plan, exercise_plan, pdf_file):
    sender = EMAIL_CONFIG["sender"]
    receiver = EMAIL_CONFIG["receiver"]
    password = EMAIL_CONFIG["app_password"]

    if not (sender and receiver and password):
        raise RuntimeError(
            "Email is not configured. Set EMAIL_SENDER, EMAIL_RECEIVER and EMAIL_APP_PASSWORD."
        )

    subject = f"AgeWell Health Alert - High Risk Patient (ID {patient_id})"
    body = f"""AGEWELL HEALTH ALERT

A high-risk patient has been detected by the AgeWell AI system.

Patient ID: {patient_id}
Age: {age}
Heart Rate: {hr}
BP: {bp}
Cholesterol: {chol}
BMI: {bmi}
Health Score: {health_score}

Recommended Plan:
{food_plan}
{exercise_plan}

Detailed report attached as PDF.

(This is an automated email generated by the AgeWell system.)
"""

    message = MIMEMultipart()
    message["From"] = sender
    message["To"] = receiver
    message["Subject"] = subject
    message.attach(MIMEText(body, "plain", "utf-8"))

    with open(pdf_file, "rb") as f:
        part = MIMEBase("application", "octet-stream")
        part.set_payload(f.read())
        encoders.encode_base64(part)
        part.add_header("Content-Disposition", f"attachment; filename={os.path.basename(pdf_file)}")
        message.attach(part)

    with smtplib.SMTP_SSL(EMAIL_CONFIG["smtp_host"], EMAIL_CONFIG["smtp_port"]) as server:
        server.login(sender, password)
        server.send_message(message)
