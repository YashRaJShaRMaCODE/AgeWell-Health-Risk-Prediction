"""PDF report generation for AgeWell patient health reports."""
import os
import uuid
from datetime import datetime

from fpdf import FPDF


def generate_health_report(pid, age, hr, bp, chol, bmi, score, risk, food, exercise,
                            logo_path=None, output_dir="reports"):
    os.makedirs(output_dir, exist_ok=True)

    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    header_bg = (0, 120, 200)
    header_text = (255, 255, 255)
    title_color = (0, 90, 160)
    text_color = (0, 0, 0)

    pdf.set_fill_color(*header_bg)
    pdf.rect(0, 0, 210, 20, "F")
    pdf.set_xy(10, 6)
    pdf.set_text_color(*header_text)
    pdf.set_font("Arial", "B", 14)
    pdf.cell(0, 8, "AgeWell - Health Data Demo Report", ln=True)

    if logo_path and os.path.exists(logo_path):
        try:
            pdf.image(logo_path, x=160, y=4, w=30)
        except Exception:
            pass

    pdf.ln(8)
    pdf.set_text_color(*text_color)
    pdf.set_font("Arial", "", 10)
    pdf.cell(0, 6, f"Generated: {datetime.now():%Y-%m-%d %H:%M:%S}", ln=True)
    pdf.set_font("Arial", "B", 11)
    pdf.set_text_color(*title_color)
    pdf.cell(0, 7, f"Patient ID: {pid}   |   Predicted Risk: {risk}", ln=True)
    pdf.ln(3)

    pdf.set_text_color(*text_color)
    pdf.set_font("Arial", "", 11)
    col_w, line_h = 95, 6
    pdf.set_x(10)
    pdf.cell(col_w, line_h, f"Age: {age}", border=0)
    pdf.cell(col_w, line_h, f"Heart Rate: {hr}", ln=True)
    pdf.set_x(10)
    pdf.cell(col_w, line_h, f"Systolic BP: {bp}", border=0)
    pdf.cell(col_w, line_h, f"Cholesterol: {chol}", ln=True)
    pdf.set_x(10)
    pdf.cell(col_w, line_h, f"BMI: {bmi}", border=0)
    pdf.cell(col_w, line_h, f"Health Score: {score}", ln=True)
    pdf.ln(6)
    pdf.set_draw_color(200, 200, 200)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(4)

    pdf.set_font("Arial", "B", 12)
    pdf.set_text_color(*title_color)
    pdf.cell(0, 7, "Personalized Food Plan", ln=True)
    pdf.set_font("Arial", "", 11)
    pdf.set_text_color(*text_color)
    pdf.multi_cell(0, 6, food)
    pdf.ln(4)

    pdf.set_font("Arial", "B", 12)
    pdf.set_text_color(*title_color)
    pdf.cell(0, 7, "Personalized Exercise Plan", ln=True)
    pdf.set_font("Arial", "", 11)
    pdf.set_text_color(*text_color)
    pdf.multi_cell(0, 6, exercise)
    pdf.ln(6)

    pdf.set_text_color(120, 120, 120)
    pdf.set_font("Arial", "I", 9)
    pdf.cell(0, 6, "Generated by AgeWell AI Health System.", ln=True)
    pdf.multi_cell(
        0, 6,
        "Research demo only. This report is not a diagnosis or medical advice and must not be used to make care decisions.",
    )

    filename = os.path.join(output_dir, f"AgeWell_Report_Patient_{pid}_{uuid.uuid4().hex[:12]}.pdf")
    pdf.output(filename)
    return filename
